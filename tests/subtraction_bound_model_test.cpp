#include "tools/hybrid/subtraction_bound_model.hpp"

#include <array>
#include <cstdint>
#include <iostream>

namespace {
struct Case {
    std::uint16_t d0, d1, limit;
    std::uint8_t marker;
    std::uint16_t expected_d0, expected_d3;
    std::uint8_t expected_marker;
    bool wrote;
};
struct NaturalCase {
    std::uint32_t d0, d1, d3;
    std::uint16_t limit, sr;
    std::uint32_t out_d0, out_d3;
    std::uint16_t out_sr;
};
}

int main() {
    using oasis::hybrid::SubtractionBoundInput;
    using oasis::hybrid::apply_subtraction_bound;
    constexpr std::array cases{
        Case{0x0010,0x0020,0x0004,0x01,0x0010,0x001C,0x01,false},
        Case{0x0030,0x0020,0x0004,0x02,0x001C,0x001C,0x02,false},
        Case{0x0001,0x0020,0x0020,0x00,0x0000,0x0000,0x48,true},
        Case{0x0001,0x0003,0x0005,0x11,0x0000,0xFFFE,0x59,true},
    };
    for (const auto& test : cases) {
        const auto result = apply_subtraction_bound({
            0xA1B20000U | test.d0, 0xC3D40000U | test.d1,
            0xE5F60077U, test.limit, test.marker, 0x2110U});
        if (static_cast<std::uint16_t>(result.d0) != test.expected_d0 ||
            static_cast<std::uint16_t>(result.d3) != test.expected_d3 ||
            result.marker != test.expected_marker || result.marker_written != test.wrote ||
            (result.d0 & 0xFFFF0000U) != 0xA1B20000U ||
            (result.d3 & 0xFFFF0000U) != 0xE5F60000U) {
            std::cerr << "subtraction bound vector mismatch\n";
            return 1;
        }
    }
    constexpr std::array natural{
        NaturalCase{0x80000002,0x00000158,0x00000003,0x0009,0x2111,0x80000002,0x0000014F,0x2109},
        NaturalCase{0x00000001,0x80000156,0x00000002,0x0009,0x2111,0x00000001,0x0000014D,0x2109},
        NaturalCase{0x83000001,0x00000122,0x00000004,0x0009,0x2111,0x83000001,0x00000119,0x2109},
        NaturalCase{0x80000002,0x00000155,0x00000001,0x0009,0x2111,0x80000002,0x0000014C,0x2109},
        NaturalCase{0x8E000001,0x83000121,0x00000003,0x0009,0x2111,0x8E000001,0x00000118,0x2109},
        NaturalCase{0x00000001,0x80000153,0x00000000,0x0009,0x2111,0x00000001,0x0000014A,0x2109},
        NaturalCase{0x80000002,0x00000152,0x00000004,0x0009,0x2111,0x80000002,0x00000149,0x2109},
        NaturalCase{0x1C000001,0x11000120,0x00000001,0x0009,0x2111,0x1C000001,0x00000117,0x2109},
        NaturalCase{0x00000001,0x80000150,0x00000003,0x0009,0x2111,0x00000001,0x00000147,0x2109},
        NaturalCase{0x27000001,0x1C00011F,0x00000000,0x0009,0x2111,0x27000001,0x00000116,0x2109},
        NaturalCase{0x80000002,0x0000014F,0x00000002,0x0009,0x2111,0x80000002,0x00000146,0x2109},
        NaturalCase{0x32000001,0x2700011E,0x00000005,0x0009,0x2111,0x32000001,0x00000115,0x2109},
        NaturalCase{0x00000001,0x8000014D,0x00000001,0x0009,0x2111,0x00000001,0x00000144,0x2109},
        NaturalCase{0x3D000001,0x3200011D,0x00000004,0x0009,0x2111,0x3D000001,0x00000114,0x2109},
        NaturalCase{0x80000002,0x0000014C,0x00000000,0x0009,0x2111,0x80000002,0x00000143,0x2109},
        NaturalCase{0x48000001,0x3D00011C,0x00000003,0x0009,0x2111,0x48000001,0x00000113,0x2109},
        NaturalCase{0x00000001,0x8000014A,0x00000004,0x0009,0x2111,0x00000001,0x00000141,0x2109},
        NaturalCase{0x53000001,0x4800011B,0x00000002,0x0009,0x2111,0x53000001,0x00000112,0x2109},
        NaturalCase{0x80000002,0x00000149,0x00000003,0x0009,0x2111,0x80000002,0x00000140,0x2109},
        NaturalCase{0x5E000001,0x5300011A,0x00000001,0x0009,0x2111,0x5E000001,0x00000111,0x2109},
        NaturalCase{0x00000001,0x80000147,0x00000002,0x0009,0x2111,0x00000001,0x0000013E,0x2109},
        NaturalCase{0x69000001,0x5E000119,0x00000000,0x0009,0x2111,0x69000001,0x00000110,0x2109},
    };
    for (const auto& test : natural) {
        const auto result = apply_subtraction_bound({test.d0, test.d1, test.d3,
            test.limit, 0U, test.sr});
        if (result.d0 != test.out_d0 || result.d3 != test.out_d3 ||
            result.sr != test.out_sr || result.marker_written) {
            std::cerr << "natural 0x9D70 replay vector mismatch\n";
            return 1;
        }
    }
    return 0;
}
