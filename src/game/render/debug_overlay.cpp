std::array<std::uint8_t, 5> get_glyph_columns(char c) noexcept {
    const auto upper = (c >= 'a' && c <= 'z') ? static_cast<char>(c - 'a' + 'A') : c;
    for (const auto& entry : kFont) {
        if (entry.ch == upper) return entry.cols;
    }
    return kFont[0].cols;
}

